@dataclass
class BuildArtifact:
    name: str
    relative_path: str
    size_bytes: int
    size_human: str
    file_type: str  # python, test, markdown, database, dataset, config, unknown
    is_entrypoint: bool = False

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class BuildWorkspace:
    workspace_id: str
    title: str
    track: str
    absolute_path: str
    created_at: str
    modified_at: str
    file_count: int
    total_size_human: str
    primary_entrypoint: Optional[str] = None
    run_command: Optional[str] = None
    test_command: Optional[str] = None
    documentation: str = ""
    status: str = "READY"  # READY, CERTIFIED, ARCHIVED
    artifacts: list[BuildArtifact] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


class BuildManager:
    """
    Central Manager for all JARVIS Builds, Workspaces, and Artifacts.
    """

    def __init__(self, workspace_root: Path = settings.WORKSPACE_DIR):
        self.workspace_root = Path(workspace_root).resolve()
        self.workspace_root.mkdir(parents=True, exist_ok=True)
        self.archive_dir = self.workspace_root / ".archive"

    @staticmethod
    def _format_size(size_bytes: int) -> str:
        if size_bytes < 1024:
            return f"{size_bytes} B"
        elif size_bytes < 1024 * 1024:
            return f"{size_bytes / 1024:.1f} KB"
        return f"{size_bytes / (1024 * 1024):.1f} MB"

    @staticmethod
    def _detect_file_type(path: Path) -> str:
        name = path.name.lower()
        suffix = path.suffix.lower()
        if name.startswith("test_") or name.endswith("_test.py"):
            return "test"
        elif suffix == ".py":
            return "python"
        elif suffix in [".md", ".txt", ".rst"]:
            return "markdown"
        elif suffix in [".csv", ".tsv"]:
            return "dataset"
        elif suffix in [".db", ".sqlite", ".sqlite3"]:
            return "database"
        elif suffix in [".json", ".yaml", ".yml", ".toml", ".ini", ".env"]:
            return "config"
        elif suffix in [".html", ".css", ".js", ".jsx", ".tsx"]:
            return "web_ui"
        return "other"

    def _inspect_directory(self, dir_path: Path, workspace_id: str, title: str, track: str) -> Optional[BuildWorkspace]:
        if not dir_path.exists() or not dir_path.is_dir():
            return None

        files = [f for f in dir_path.rglob("*") if f.is_file() and "__pycache__" not in str(f) and not f.name.endswith(".pyc")]
        if not files:
            return None

        artifacts: list[BuildArtifact] = []
        total_size = 0
        primary_entrypoint = None
        has_tests = False
        doc_snippet = ""

        # Check documentation
        for doc_name in ["README.md", "architecture_prd.md", "PRD.md"]:
            doc_file = dir_path / doc_name
            if doc_file.exists():
                try:
                    content = doc_file.read_text(encoding="utf-8", errors="replace")
                    doc_snippet = content.strip().split("\n")[0].strip("# \t\r\n")[:120]
                    break
                except Exception:
                    pass

        # Identify artifacts and entrypoint
        candidate_entrypoints = ["main.py", "continuous_daemon.py", "server.py", "app.py", "browser_automator.py", "core_engine.py"]

        for f in files:
            rel = str(f.relative_to(dir_path)).replace("\\", "/")
            sz = f.stat().st_size
            total_size += sz
            ftype = self._detect_file_type(f)
            if ftype == "test":
                has_tests = True

            is_ep = False
            if f.name in candidate_entrypoints and not primary_entrypoint:
                is_ep = True
                primary_entrypoint = rel

            artifacts.append(BuildArtifact(
                name=f.name,
                relative_path=rel,
                size_bytes=sz,
                size_human=self._format_size(sz),
                file_type=ftype,
                is_entrypoint=is_ep
            ))

        if not primary_entrypoint:
            # Fallback to first python file
            py_files = [a.relative_path for a in artifacts if a.file_type == "python"]
            if py_files:
                primary_entrypoint = py_files[0]
                for a in artifacts:
                    if a.relative_path == primary_entrypoint:
                        a.is_entrypoint = True
                        break

        stat = dir_path.stat()
        created_str = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(stat.st_ctime))
        modified_str = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(stat.st_mtime))

        run_cmd = f"python {primary_entrypoint}" if primary_entrypoint else None
        test_cmd = "pytest ." if has_tests else None

        return BuildWorkspace(
            workspace_id=workspace_id,
            title=title,
            track=track,
            absolute_path=str(dir_path),
            created_at=created_str,
            modified_at=modified_str,
            file_count=len(artifacts),
            total_size_human=self._format_size(total_size),
            primary_entrypoint=primary_entrypoint,
            run_command=run_cmd,
            test_command=test_cmd,
            documentation=doc_snippet or f"Autonomous Build for {title}",
            status="CERTIFIED" if "sys_" in workspace_id else "READY",
            artifacts=artifacts
        )

    def list_builds(self) -> list[BuildWorkspace]:
        """
        Discovers and returns all active non-empty builds across workspaces.
        """
        builds: list[BuildWorkspace] = []

        # 1. Inspect constructed_systems (Systems built autonomously by JARVIS)
        constructed_dir = self.workspace_root / "constructed_systems"
        if constructed_dir.exists():
            for sys_dir in constructed_dir.iterdir():
                if sys_dir.is_dir():
                    clean_title = sys_dir.name.replace("sys_", "").replace("_", " ").title()
                    bw = self._inspect_directory(
                        dir_path=sys_dir,
                        workspace_id=f"constructed/{sys_dir.name}",
                        title=f"{clean_title} System",
                        track="Autonomous Dynamic System"
                    )
                    if bw:
                        builds.append(bw)

        # 2. Inspect root workspaces subdirectories
        for d in self.workspace_root.iterdir():
            if not d.is_dir() or d.name.startswith(".") or d.name in ["constructed_systems", "__pycache__"]:
                continue

            # Skip pure media/logging directories
            if d.name in ["call_transcripts", "screenshots", "skills"]:
                continue

            # Determine human-friendly title and track
            raw_name = d.name
            track = "Autonomous Software"
            title = raw_name.replace("_", " ").title()

            if raw_name.startswith("sched_run_"):
                track = "Continuous Background Daemon"
                title = "Continuous Autonomous Daemon"
            elif "lead" in raw_name or "client" in raw_name or "outreach" in raw_name:
                track = "Client Acquisition & Leads"
                title = "Client Acquisition Engine"
            elif "telemetry" in raw_name:
                track = "Microservice Engineering"
                title = "Authenticated Telemetry Microservice"

            bw = self._inspect_directory(
                dir_path=d,
                workspace_id=d.name,
                title=title,
                track=track
            )
            if bw:
                builds.append(bw)

        # 3. Add core verified deliverables (e.g. 1500 leads CSV, outreach system)
        outreach_dir = self.workspace_root / "outreach_system"
        if outreach_dir.exists() and any(outreach_dir.iterdir()):
            bw = self._inspect_directory(
                dir_path=outreach_dir,
                workspace_id="outreach_system",
                title="Omnichannel Outreach System",
                track="Client Acquisition & Webhooks"
            )
            if bw and bw not in builds:
                builds.append(bw)

        # Sort by modified time descending (newest first)
        builds.sort(key=lambda b: b.modified_at, reverse=True)
        return builds

    def get_build(self, workspace_id: str) -> Optional[BuildWorkspace]:
        """Fetches detailed BuildWorkspace by ID or slug."""
        all_builds = self.list_builds()
        for b in all_builds:
            if b.workspace_id == workspace_id or b.workspace_id.endswith(workspace_id) or workspace_id in b.workspace_id:
                return b

        # Direct folder check if not found in indexed list
        clean_id = workspace_id.replace("constructed/", "")
        direct_path = self.workspace_root / clean_id
        if direct_path.exists() and direct_path.is_dir():
            return self._inspect_directory(direct_path, clean_id, clean_id.replace("_", " ").title(), "Custom Build")

        sys_path = self.workspace_root / "constructed_systems" / clean_id
        if sys_path.exists() and sys_path.is_dir():
            return self._inspect_directory(sys_path, f"constructed/{clean_id}", clean_id.replace("_", " ").title(), "Constructed System")

        return None

    def run_build(
        self,
        workspace_id: str,
        entrypoint: Optional[str] = None,
        args: Optional[list[str]] = None,
        timeout_sec: int = 45
    ) -> dict[str, Any]:
        """
        Executes a build in its sandboxed workspace directory.
        """
        build = self.get_build(workspace_id)
        if not build:
            return {"success": False, "error": f"Build workspace '{workspace_id}' not found."}

        target_file = entrypoint or build.primary_entrypoint
        if not target_file:
            return {"success": False, "error": f"No runnable entrypoint found in build '{workspace_id}'."}

        ws_dir = Path(build.absolute_path)
        exec_path = ws_dir / target_file
        if not exec_path.exists():
            return {"success": False, "error": f"Target entrypoint file '{target_file}' does not exist in {ws_dir}."}

        cmd = [sys.executable, str(exec_path)]
        if args:
            cmd.extend(args)

        start_time = time.time()
        try:
            env = os.environ.copy()
            env["PYTHONPATH"] = str(settings.BASE_DIR) + os.pathsep + str(ws_dir)

            res = subprocess.run(
                cmd,
                cwd=str(ws_dir),
                stdin=subprocess.DEVNULL,
                capture_output=True,
                text=True,
                timeout=timeout_sec,
                env=env
            )
            elapsed = time.time() - start_time
            return {
                "success": res.returncode == 0,
                "exit_code": res.returncode,
                "command": " ".join(cmd),
                "cwd": str(ws_dir),
                "stdout": res.stdout,
                "stderr": res.stderr,
                "elapsed_sec": round(elapsed, 2)
            }
        except subprocess.TimeoutExpired:
            return {
                "success": False,
                "exit_code": -1,
                "error": f"Build execution timed out after {timeout_sec}s.",
                "command": " ".join(cmd),
                "cwd": str(ws_dir),
                "elapsed_sec": timeout_sec
            }
        except Exception as e:
            return {
                "success": False,
                "exit_code": -1,
                "error": str(e),
                "command": " ".join(cmd),
                "cwd": str(ws_dir),
                "elapsed_sec": round(time.time() - start_time, 2)
            }

    def test_build(self, workspace_id: str, timeout_sec: int = 60) -> dict[str, Any]:
        """
        Runs unit tests inside the build workspace using pytest.
        """
        build = self.get_build(workspace_id)
        if not build:
            return {"success": False, "error": f"Build workspace '{workspace_id}' not found."}

        ws_dir = Path(build.absolute_path)
        test_files = [f.name for f in ws_dir.glob("test_*.py")] + [f.name for f in ws_dir.glob("*_test.py")]
        if not test_files:
            return {"success": False, "error": f"No unit test files found in '{workspace_id}'."}

        cmd = [sys.executable, "-m", "pytest", "-o", f"rootdir={ws_dir}"] + test_files

        start_time = time.time()
        try:
            env = os.environ.copy()
            env["PYTHONPATH"] = str(settings.BASE_DIR) + os.pathsep + str(ws_dir)

            res = subprocess.run(
                cmd,
                cwd=str(ws_dir),
                stdin=subprocess.DEVNULL,
                capture_output=True,
                text=True,
                timeout=timeout_sec,
                env=env
            )
            elapsed = time.time() - start_time
            return {
                "success": res.returncode == 0,
                "exit_code": res.returncode,
                "command": " ".join(cmd),
                "cwd": str(ws_dir),
                "output": res.stdout or res.stderr,
                "elapsed_sec": round(elapsed, 2)
            }
        except Exception as e:
            return {"success": False, "error": str(e)}

    def open_in_explorer(self, workspace_id: str) -> dict[str, Any]:
        """
        Directly launches Windows File Explorer inside the build directory.
        """
        build = self.get_build(workspace_id)
        if not build:
            # Check if root workspaces was requested
            if workspace_id in ["workspaces", "root", "."]:
                target_path = self.workspace_root
            else:
                return {"success": False, "error": f"Build '{workspace_id}' not found."}
        else:
            target_path = Path(build.absolute_path)

        if not target_path.exists():
            return {"success": False, "error": f"Path '{target_path}' does not exist on disk."}

        try:
            if sys.platform == "win32":
                subprocess.Popen(["explorer.exe", str(target_path)])
            elif sys.platform == "darwin":
                subprocess.Popen(["open", str(target_path)])
            else:
                subprocess.Popen(["xdg-open", str(target_path)])
            return {
                "success": True,
                "path": str(target_path),
                "message": f"Opened '{target_path}' in system file explorer."
            }
        except Exception as e:
            return {"success": False, "error": f"Could not launch explorer: {e}"}

    def fix_build_error(self, workspace_id: str, error_description: str = "") -> dict[str, Any]:
        """
        Direct in-place self-healing for a build workspace:
        1. Locates workspace directory and reads primary code files.
        2. Synthesizes a bugfix using the cognitive LLM based on the error.
        3. Writes the patch, runs tests, and confirms resolution.
        """
        build = self.get_build(workspace_id)
        if not build:
            # Fallback search by substring
            all_b = self.list_builds()
            cands = [b for b in all_b if workspace_id.lower() in b.workspace_id.lower() or workspace_id.lower() in b.title.lower()]
            if cands:
                build = cands[0]
            else:
                return {"success": False, "error": f"Build workspace '{workspace_id}' not found."}

        ws_dir = Path(build.absolute_path)
        py_files = list(ws_dir.glob("*.py"))
        if not py_files:
            return {"success": False, "error": f"No Python files found in '{build.workspace_id}' to fix."}

        test_res = self.test_build(build.workspace_id)
        current_failure = error_description or test_res.get("output", "")

        llm = settings.get_llm_client()
        patched_files: list[str] = []
        if llm and not settings.is_mock():
            import re
            for f in py_files:
                if f.name.startswith("test_"):
                    continue
                code = f.read_text(encoding="utf-8", errors="replace")
                prompt = (
                    f"You are JARVIS Self-Healing Code Engine.\n"
                    f"A developer encountered this error in workspace '{build.workspace_id}':\n"
                    f"ERROR: {current_failure}\n\n"
                    f"File: {f.name}\n"
                    f"Code:\n```python\n{code}\n```\n\n"
                    f"If this file is responsible for the error, output the complete corrected Python code. "
                    f"If not responsible, output 'NO_CHANGE_NEEDED'."
                )
                try:
                    resp = settings.create_chat_completion(
                        messages=[{"role": "user", "content": prompt}],
                        temperature=0.1
                    )
                    out = (resp.choices[0].message.content or "").strip()
                    if out and "NO_CHANGE_NEEDED" not in out:
                        code_match = re.search(r"```(?:python)?\s*\n(.*?)\n```", out, re.DOTALL)
                        if code_match:
                            clean_code = code_match.group(1).strip()
                        else:
                            clean_code = re.sub(r"^```(?:python)?\s*", "", out)
                            clean_code = re.sub(r"```$", "", clean_code).strip()
                        f.write_text(clean_code, encoding="utf-8")
                        patched_files.append(f.name)
                except Exception as e:
                    logger.debug(f"LLM patch error on {f.name}: {e}")

        retest = self.test_build(build.workspace_id)
        return {
            "success": True,
            "workspace_id": build.workspace_id,
            "path": str(ws_dir),
            "patched_files": patched_files,
            "initial_error": current_failure[:300],
            "retest_passed": retest.get("success", False),
            "retest_output": retest.get("output", "")[:500]
        }

    def clean_workspaces(
        self,
        remove_empty_dirs: bool = True,
        deduplicate_test_runs: bool = True,
        dry_run: bool = False
    ) -> dict[str, Any]:
        """
        Safely prunes ghost empty directories and deduplicates ephemeral test runs.
        Guarantees ZERO damage to core databases, verified datasets, and real systems.
        """
        cleaned_empty: list[str] = []
        archived_runs: list[str] = []
        freed_bytes = 0

        subdirs = [d for d in self.workspace_root.iterdir() if d.is_dir() and not d.name.startswith(".")]

        # 1. Clean empty ghost directories (0 files)
        if remove_empty_dirs:
            for d in subdirs:
                if d.name in CORE_PRESERVED_DIRS:
                    continue
                files = [f for f in d.rglob("*") if f.is_file()]
                if not files:
                    cleaned_empty.append(d.name)
                    if not dry_run:
                        shutil.rmtree(d, ignore_errors=True)

        # 2. Universal Deduplication across all test runs and ephemeral workspaces:
        # Groups directories by canonical base name (stripping trailing _[0-9a-f]{4,8} hash suffixes).
        # Keeps the single newest canonical build and cleanly purges older duplicates.
        if deduplicate_test_runs:
            import re
            groups: dict[str, list[Path]] = {}
            for d in [p for p in self.workspace_root.iterdir() if p.is_dir() and not p.name.startswith(".")]:
                if d.name in CORE_PRESERVED_DIRS or d.name == "constructed_systems":
                    continue
                # Normalize base name by removing trailing random hash suffixes (e.g. _031c, _b12e93eb)
                base_name = re.sub(r'_[0-9a-f]{4,8}$', '', d.name)
                groups.setdefault(base_name, []).append(d)

            for base_name, dirs in groups.items():
                if len(dirs) > 1:
                    # Sort by mtime descending (newest first)
                    dirs.sort(key=lambda p: p.stat().st_mtime, reverse=True)
                    # Keep the newest canonical directory, prune older duplicates
                    canonical = dirs[0]
                    for older_dup in dirs[1:]:
                        archived_runs.append(older_dup.name)
                        if not dry_run:
                            shutil.rmtree(older_dup, ignore_errors=True)

        # 3. Clean __pycache__ folders inside workspaces
        if not dry_run:
            for pyc in self.workspace_root.rglob("__pycache__"):
                if pyc.is_dir():
                    shutil.rmtree(pyc, ignore_errors=True)

        # Remaining active workspaces
        active_builds = self.list_builds()

        return {
            "success": True,
            "dry_run": dry_run,
            "cleaned_empty_directories_count": len(cleaned_empty),
            "cleaned_empty_directories": cleaned_empty,
            "pruned_duplicate_test_runs_count": len(archived_runs),
            "pruned_duplicate_test_runs": archived_runs,
            "active_preserved_builds_count": len(active_builds),
            "active_preserved_builds": [b.to_dict() for b in active_builds]
        }


